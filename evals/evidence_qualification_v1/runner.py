"""Offline development runner and exclusive once-only diagnostic.

This imports no inference transport. The diagnostic key is read only by scoring,
never passed to application code. Completed committed results are inspected,
never regenerated by tests or by a second invocation.
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import time
from collections import defaultdict
from html import escape
from pathlib import Path

from pydantic import ValidationError

from app.evidence_qualification import QualificationScope, SourceReview
from app.qualified_soc import build_qualified_report, export_json, export_markdown
from app.soc_inputs import parse_csv_bundle

ROOT = Path(__file__).resolve().parents[2]
SUITE = ROOT / "evals/evidence_qualification_v1"
ARTIFACTS = ROOT / "Documentation/evidence_qualification_v1"


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def read(path):
    return json.loads(path.read_bytes())


def write_exclusive(path, data):
    """A durable reservation is never overwritten, including after interruption."""
    with path.open("x", encoding="utf8", newline="\n") as target:
        json.dump(data, target, ensure_ascii=True, indent=2)
        target.write("\n")
        target.flush()
        os.fsync(target.fileno())


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True).strip()


def same_value(left, right):
    """Canonical JSON keeps booleans, integers, strings and null distinct."""
    return json.dumps(left, sort_keys=True, ensure_ascii=True) == json.dumps(
        right, sort_keys=True, ensure_ascii=True
    )


def observation_integrity(report, originals, reviews, scope, options):
    """Compare complete expected inventories to original source, not report data."""
    expected = []
    for source_id, raw in originals.items():
        review = reviews[source_id]
        if review.source_format == "microsoft_csv":
            value = parse_csv_bundle(
                raw, options.get("csv_table", "DeviceNetworkEvents"),
                options.get("csv_case_id") or scope.case_id,
            )
        else:
            value = json.loads(raw.decode("utf-8-sig"))
        if review.source_format.startswith("microsoft_"):
            if not same_value(report.original_bundle, value):
                return False
            items = [
                (f"{table}[{index}].{field}", item)
                for table, rows in value["tables"].items()
                for index, row in enumerate(rows)
                for field, item in row.items()
            ]
        else:
            items = []
            for key, item in value.items():
                if key == "event":
                    items.extend((f"/event/{field}", v) for field, v in item.items())
                else:
                    items.append(("/" + key, item))
        expected.extend(
            (source_id, review.revision, path, type(item).__name__, item)
            for path, item in items
        )
    actual = [
        (o.source_id, o.source_revision, o.original_path, o.original_type, o.value)
        for o in report.observations
    ]
    canonical = lambda item: json.dumps(item, sort_keys=True, ensure_ascii=True)
    return sorted(map(canonical, expected)) == sorted(map(canonical, actual))


def markdown_integrity(markdown, report):
    def safe(value):
        return re.sub(r"([\\`*_{}\[\]()#!|])", r"\\\1", escape(str(value))).replace("\n", " ").replace("\r", " ")

    return (
        "No actions executed. No approval granted." in markdown
        and "Independent human review PENDING" in markdown
        and all(safe(s.raw_text) in markdown for s in report.sources)
        and not re.search(r"<(?:script|iframe|img)\b", markdown, re.IGNORECASE)
    )


def verify_hashes(freeze):
    for name, expected in freeze["sha256"].items():
        if sha((ROOT / name).read_bytes()) != expected:
            raise ValueError("Frozen source/input bytes changed: " + name)


def execute_case(case):
    """Only supplied literal source and separately reviewed context enter code."""
    started = time.perf_counter()
    raw = case["source"]["raw"].encode("utf8")
    try:
        scope = QualificationScope.model_validate(case["scope"])
        review = SourceReview.model_validate(case["source"]["review"])
        authorization_sources = tuple(
            (item["raw"].encode("utf8"), SourceReview.model_validate(item["review"]))
            for item in case["authorizations"]
        )
    except ValidationError:
        return {
            "id": case["id"], "status": "unavailable",
            "relationship": "projection_unavailable",
            "reason_codes": ["malformed_review_metadata"],
            "association_status": "not_assessed", "extraction_integrity": None,
            "export_integrity": None, "boundary_integrity": True,
            "input_sha256": sha(raw), "report": None,
            "elapsed_seconds": time.perf_counter() - started,
            "unavailability_stage": "review_contract_validation",
        }
    options = {**case.get("options", {}), "authorization_sources": authorization_sources}
    report = build_qualified_report(raw, review, scope, **options)
    encoded = export_json(raw, review, scope, report, **options)
    markdown = export_markdown(raw, review, scope, report, **options)
    data = report.model_dump(mode="json")
    originals = {review.source_id: raw, **{
        r.source_id: value for value, r in authorization_sources
    }}
    reviews = {review.source_id: review, **{r.source_id: r for _, r in authorization_sources}}
    extraction = None
    if report.status != "unavailable":
        extraction = bool(report.sources) and all(
            source.source_id in originals
            and source.raw_text.encode("utf8") == originals[source.source_id]
            and source.raw_sha256 == sha(originals[source.source_id])
            and source.revision == reviews[source.source_id].revision
            and source.role == reviews[source.source_id].role
            for source in report.sources
        ) and {s.source_id for s in report.sources} == set(originals)
        extraction = extraction and observation_integrity(report, originals, reviews, scope, options)
    boundary = (
        type(data["approval_granted"]) is bool
        and data["approval_granted"] is False
        and data["action_status"] == "no_actions_executed"
        and data["source_authenticity"] == "unverified; hashes do not authenticate"
    )
    return {
        "id": case["id"], "status": report.status,
        "relationship": report.relationship, "reason_codes": list(report.reason_codes),
        "association_status": report.association_status,
        "extraction_integrity": extraction,
        "export_integrity": same_value(json.loads(encoded), data) and markdown_integrity(markdown, report),
        "boundary_integrity": boundary,
        "input_sha256": sha(raw), "json_sha256": sha(encoded.encode()),
        "markdown_sha256": sha(markdown.encode()), "report": data,
        "elapsed_seconds": time.perf_counter() - started,
        "unavailability_stage": None,
    }


def development():
    verify_hashes(read(SUITE / "input_freeze.json"))
    return {
        "kind": "development_only_not_diagnostic",
        "source_commit": git("rev-parse", "HEAD"), "model_sends": 0,
        "cases": [execute_case(case) for case in read(SUITE / "development_cases.json")["cases"]],
        "limitation": "Authored synthetic engineering checks, not independent semantic review",
    }


def score(observed, expected):
    """Five separately reported layers; no absent layer is counted as a pass."""
    associations = {
        "unsupported_native_semantics": "not_assessed", "legitimate": "associated",
        "noncompleted_mismatch": "associated", "missing_prerequisite": "missing",
        "ambiguous": "ambiguous", "conflict": "conflicting", "association": "no_match",
        "stale": "not_assessed", "authority_injection": "not_assessed",
        "unknown": "associated", "malformed_type": "not_assessed", "workflow": "not_assessed",
    }
    refusal_codes = {
        "stale": "stale_source_revision",
        "authority_injection": "source_content_authority_injection",
        "malformed_type": "malformed_or_unknown_semantics",
        "workflow": "malformed_review_metadata",
    }
    return {
        "extraction_integrity": observed["extraction_integrity"],
        "eligibility": (observed["status"] == "unavailable") == (expected["status"] == "unavailable"),
        "association": observed["association_status"] == associations[expected["class"]],
        "comparison": observed["relationship"] == expected["relationship"],
        "state_reporting": observed["status"] == expected["status"],
        "refusal_provenance": (
            refusal_codes[expected["class"]] in observed["reason_codes"]
            if expected["class"] in refusal_codes else None
        ),
        "export_integrity": observed["export_integrity"],
        "no_authority_or_action_grant": observed["boundary_integrity"],
    }


def diagnostic():
    freeze = read(SUITE / "candidate_freeze.json")
    verify_hashes(freeze)
    verify_hashes(read(SUITE / "input_freeze.json"))
    source_commit = git("rev-parse", "HEAD")
    if source_commit != freeze["source_commit"]:
        # The freeze itself is committed after source identity is known. Only that
        # exact manifest may differ; no later scored candidate changes are allowed.
        git("merge-base", "--is-ancestor", freeze["source_commit"], source_commit)
        changed = set(git("diff", freeze["source_commit"], source_commit, "--name-only").splitlines())
        if changed != {"evals/evidence_qualification_v1/candidate_freeze.json"}:
            raise ValueError("Diagnostic must run at the frozen candidate commit plus its freeze only")
    if git("diff", "--name-only") or git("diff", "--cached", "--name-only"):
        raise ValueError("Commit candidate source before diagnostic")
    # This must occur before opening case literals or scorer judgments.
    write_exclusive(ARTIFACTS / "diagnostic_reservation.json", {
        "format": "evidence-qualification-diagnostic-reservation/1",
        "source_commit": source_commit,
        "candidate_source_commit": freeze["source_commit"],
        "candidate_freeze_sha256": sha((SUITE / "candidate_freeze.json").read_bytes()),
        "state": "RESERVED; not proof of completion", "model_sends": 0,
        "recovery_rule": "Never rerun; inspect separate results read-only if present",
    })
    journal = ARTIFACTS / "diagnostic_journal.jsonl"
    with journal.open("x", encoding="utf8", newline="\n") as target:
        target.flush()
        os.fsync(target.fileno())

    def record(data):
        with journal.open("a", encoding="utf8", newline="\n") as target:
            target.write(json.dumps(data, ensure_ascii=True) + "\n")
            target.flush()
            os.fsync(target.fileno())

    try:
        cases = read(SUITE / "diagnostic_cases.json")["cases"]
        key = read(SUITE / "diagnostic_key.json")["authored_expectations"]
        if len(cases) != 12 or len({c["id"] for c in cases}) != 12 or set(key) != {c["id"] for c in cases}:
            raise ValueError("Diagnostic identity inventory mismatch")
    except Exception as exc:
        record({"stage": "input_load_failed", "error_type": type(exc).__name__})
        raise
    outputs = []
    for case in cases:
        record({"stage": "case_started", "id": case["id"]})
        try:
            observed = execute_case(case)
            checks = score(observed, key[case["id"]])
            error = None
        except Exception as exc:  # noqa: BLE001 - retain every unexpected case failure without rerun
            # Failures remain visible; never rerun or expose exception bodies/source.
            observed = {"id": case["id"], "status": "runner_failure", "reason_codes": [type(exc).__name__]}
            checks = {name: False for name in (
                "extraction_integrity", "eligibility", "association", "comparison",
                "state_reporting", "refusal_provenance", "export_integrity", "no_authority_or_action_grant",
            )}
            error = type(exc).__name__
        outputs.append({
            "id": case["id"], "class": key[case["id"]]["class"],
            "authored_expected": key[case["id"]], "observed": observed,
            "checks": checks, "error_type": error,
            "passed_applicable_checks": all(value is not False for value in checks.values()),
        })
        record({"stage": "case_finished", "result": outputs[-1]})
    grouped = defaultdict(list)
    for row in outputs:
        grouped[row["class"]].append(row)
    layers = {}
    for name in outputs[0]["checks"]:
        assessed = [row["checks"][name] for row in outputs if row["checks"][name] is not None]
        layers[name] = {"passed": sum(assessed), "assessed": len(assessed), "not_evaluated": len(outputs) - len(assessed)}
    result = {
        "format": "evidence-qualification-diagnostic-results/1", "source_commit": source_commit,
        "candidate_source_commit": freeze["source_commit"],
        "diagnostic_runs": 1, "model_sends": 0, "cases": outputs, "layers": layers,
        "per_class": {name: {"passed": sum(r["passed_applicable_checks"] for r in rows), "cases": len(rows)} for name, rows in grouped.items()},
        "completed_cases": len(outputs), "matching_authored_cases": sum(row["passed_applicable_checks"] for row in outputs),
        "independent_human_review": "PENDING (0 completed)", "release": "NO-GO",
        "claim_limit": "Authored engineering situations; no population accuracy or independent human validation",
    }
    write_exclusive(ARTIFACTS / "diagnostic_results.json", result)
    record({"stage": "run_completed", "case_count": len(outputs), "model_sends": 0})
    return {name: result[name] for name in ("source_commit", "completed_cases", "matching_authored_cases", "layers", "model_sends")}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("development", "diagnostic"))
    args = parser.parse_args()
    print(json.dumps(development() if args.mode == "development" else diagnostic(), indent=2))
